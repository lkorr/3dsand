/* compile_dungeon.mjs — dungeon.json -> shell.json + shell.bin, PLAN_dungeons
 * §3.4 / §3.4.1 (the engine's schema: D1 amendment).
 *
 *   node scripts/compile_dungeon.mjs <id>          compile assets/dungeons/<id>/
 *   node scripts/compile_dungeon.mjs --all         every assets/dungeons/<id>/dungeon.json (bases before variants)
 *   node scripts/compile_dungeon.mjs <id> --check  exit 1 if shell.json / shell.bin (and a variant's refs.json) are stale (no write)
 *   node scripts/compile_dungeon.mjs <id> --validate   also print the validation panel
 *
 * Uses the SAME assets/editor/dungeon/dungeongen.js the tuner's Dungeons tab
 * runs, so the two produce byte-identical files. The shell's header carries
 * the FNV-1a of the dungeon.json bytes, CRs dropped (sourceHash): the
 * engine's dungeon-format gate compares it to tell a stale shell, and holds
 * shell.bin to shell.json by CONTENT (`sandvox.exe --dungeon-bake <id>`
 * rewrites the .bin with the engine's own writer if the two ever disagree).
 *
 * VARIANTS (D8, PLAN_dungeons "Portability"): a dungeon.json with "extends"
 * is resolved against its base (chains flattened, cycles refused) and
 * compiled into ITS OWN shell; its refs.json is WRITTEN here too (the base's
 * refs, waynodes re-adopted from the variant's geometry, refs inside removed
 * pieces dropped, the variant's refsPatch applied), stamped as generated, so
 * the engine and the refs loader need no change. The shell's extra
 * `source.resolvedHash` covers the resolved source (base included): --check
 * flags a variant whose BASE changed, even though its own bytes did not.
 *
 * A dungeon placed on a map is worldgen input: recompiling one moves the
 * world hash (one `--selftest --rebaseline`, a notification, not a regression).
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'fs';
import { fileURLToPath, pathToFileURL } from 'url';
import { dirname, join } from 'path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DG = await import(pathToFileURL(join(ROOT, 'assets/editor/dungeon/dungeongen.js')).href);
const E = await import(pathToFileURL(join(ROOT, 'assets/editor/dungeon/ui_entities.js')).href);
const MATS = JSON.parse(readFileSync(join(ROOT, 'assets/materials/materials.json'), 'utf8')).materials.map(m => m.id);
const DIR = join(ROOT, 'assets', 'dungeons');

const args = process.argv.slice(2);
const flag = (f) => args.includes(f);
const loadBase = (id) => { const f = join(DIR, id, 'dungeon.json'); return existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')) : null; };

let ids = flag('--all')
  ? readdirSync(DIR, {withFileTypes: true}).filter(e => e.isDirectory() && existsSync(join(DIR, e.name, 'dungeon.json'))).map(e => e.name).sort()
  : args.filter(a => !a.startsWith('--'));
if (!ids.length) { console.error('usage: node scripts/compile_dungeon.mjs <id>|--all [--check] [--validate]'); process.exit(2); }
// Bases before variants: a variant's chain depth orders it (a cycle sorts last and fails there).
const depth = (id, seen) => { seen = seen || []; const d = loadBase(id); if (!d || !DG.isVariant(d) || seen.includes(id) || seen.length > DG.VARIANT_MAX_DEPTH) return 0; return 1 + depth(d.extends, seen.concat(id)); };
ids = ids.map(id => ({id, k: depth(id)})).sort((a, b) => a.k - b.k || (a.id < b.id ? -1 : 1)).map(x => x.id);

/** A variant's resolved refs.json text, or null for a plain dungeon. */
function variantRefsText(id, d, prog) {
  if (!DG.isVariant(d)) return null;
  const res = DG.resolveDungeon(d, loadBase);
  const baseId = d.extends;
  const baseRefsFile = join(DIR, baseId, (loadBase(baseId) || {}).refs || 'refs.json');
  const base = existsSync(baseRefsFile) ? E.readRefs(readFileSync(baseRefsFile, 'utf8')) : {about: '', refs: []};
  // The base's refs are in ITS anchor frame (its entrance socket); shift them
  // if the variant moved the entrance.
  const baseProg = DG.compile(loadBase(baseId), {id: baseId, loadBase});
  const shift = [0, 1, 2].map(i => baseProg.entrance.dungeonPos[i] - prog.entrance.dungeonPos[i]);
  const baseRefs = base.refs.map(r => Object.assign({}, r, {pos: r.pos.map((v, i) => v + shift[i])}));
  const {refs, notes} = DG.resolveVariantRefs(baseRefs, d, prog, res.removed, prog.entrance.dungeonPos);
  for (const n of notes) console.log('  ' + id + ' refs: ' + n);
  const about = 'GENERATED by scripts/compile_dungeon.mjs from ' + res.chain.concat(id).join(' -> ') +
                ' (the base\'s refs + this variant\'s refsPatch): edit the variant\'s dungeon.json, not this file.' + (d.about ? ' ' + d.about : '');
  return E.writeRefs(id, about, refs);
}

let bad = 0;
for (const id of ids) {
  const dir = join(DIR, id), src = join(dir, 'dungeon.json');
  if (!existsSync(src)) { console.error(id + ': no ' + src); bad++; continue; }
  const text = readFileSync(src, 'utf8');
  let d;
  try { d = JSON.parse(text); } catch (e) { console.error(id + ': dungeon.json does not parse: ' + e.message); bad++; continue; }
  // A hand-written shell (D1's _fixture: kit "fixture") has no generator to recompile it from;
  // --all skips it, naming it, instead of dying on the unknown kit. Its gate is dungeon-format.
  if (!DG.isVariant(d)) {
    const foreign = (d.pieces || []).map(pc => pc.kit).filter(k => !DG.KITS[k]);
    if (foreign.length) {
      if (flag('--all')) { console.log(id + ': skipped (hand-written shell; kit ' + foreign[0] + ' has no generator)'); continue; }
      console.error(id + ': unknown kit ' + foreign[0]); bad++; continue;
    }
  }
  let prog, refsText;
  try {
    prog = DG.compile(d, {id, sourceText: text, materials: MATS, loadBase});
    refsText = variantRefsText(id, d, prog);
  } catch (e) { console.error(id + ': ' + e.message); bad++; continue; }
  const json = DG.emitShellJson(prog);
  const bin = DG.emitShellBin(prog);
  const out = join(dir, 'shell.json'), outBin = join(dir, 'shell.bin'), outRefs = join(dir, (d.refs || 'refs.json'));
  const nScatter = prog.prims.reduce((a, p) => a + (p.scatter ? p.scatter.length : 0), 0);
  const line = id + (DG.isVariant(d) ? ' (variant of ' + d.extends + ')' : '') + ': ' + prog.pieces.length + ' pieces, ' + prog.prims.length + ' prims, ' + nScatter + ' scatter rules, ' +
               prog.props.templates.length + ' prop templates / ' + prog.props.instances.length + ' instances, ' + prog.waynodes.length + ' waynodes, ' +
               prog.refs.length + ' ref suggestions; bounds ' + JSON.stringify(prog.bounds) + '; worst 64^3 cell ' + prog.limits.primsPerCell + ' prims / ' +
               prog.limits.instancesPerCell + ' instances; sourceHash ' + prog.sourceHash;
  for (const e of prog.errors) console.error('  ERROR ' + (e.piece || '-') + ': ' + e.msg);
  if (prog.errors.length) bad++;
  if (flag('--check')) {
    const cur = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r/g, '') : null;   // a CRLF checkout is not stale
    const curBin = existsSync(outBin) ? readFileSync(outBin) : null;
    const binOk = curBin && Buffer.compare(curBin, Buffer.from(bin)) === 0;
    const refsOk = refsText === null || (existsSync(outRefs) && readFileSync(outRefs, 'utf8').replace(/\r/g, '') === refsText);
    if (cur !== json || !binOk || !refsOk) {
      const what = cur !== json ? 'json' : !binOk ? 'bin' : 'refs.json';
      const why = DG.isVariant(d) && cur && !cur.includes('"resolvedHash":' + prog.source.resolvedHash) ? ' (its base ' + d.extends + ' changed)' : '';
      console.error(id + ': ' + what + ' is STALE' + why + ' (run node scripts/compile_dungeon.mjs ' + id + ')'); bad++;
    } else console.log(id + ': shell.json + shell.bin' + (refsText !== null ? ' + refs.json' : '') + ' current');
  } else {
    writeFileSync(out, json);
    writeFileSync(outBin, bin);
    if (refsText !== null) writeFileSync(outRefs, refsText);
    console.log(line + '; shell.bin ' + bin.length + ' B' + (refsText !== null ? '; refs.json generated' : ''));
  }
  if (flag('--validate')) for (const v of DG.validate(d, {materials: MATS, loadBase})) console.log('  ' + v.severity.padEnd(5) + ' ' + v.code.padEnd(11) + ' ' + (v.piece || '-') + ': ' + v.msg);
}
process.exit(bad ? 1 : 0);
