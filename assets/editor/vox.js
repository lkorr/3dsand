/* ============================================================================
   vox.js — MagicaVoxel .vox reader/writer, zero dependencies.

   Why hand-written: the JS .vox libraries on npm silently drop scene chunks
   (nTRN/nGRP/nSHP) and some rewrite the palette, both of which would corrupt
   the engine's "palette index == material ID" convention. This module reads
   what it understands, skips what it does not, and writes the minimal file
   MagicaVoxel and src/sim/voxload.cpp both accept.

   Spec facts that are easy to get wrong, encoded once here:

   - Chunk header is id[4] chars, then contentBytes:i32, then childrenBytes:i32,
     all little-endian. A chunk's total size is 12 + content + children.
   - XYZI voxel records are 4 BYTES: x, y, z, colorIndex. Not shorts. That is
     why dimensions cap at 256.
   - PALETTE OFF-BY-ONE. The RGBA chunk holds 256 entries, and entry i of that
     array is palette index i+1. Index 0 is "empty" and has no RGBA entry.
     In this project palette index == engine material ID, so material ID i's
     colour must be written at RGBA array position i-1. Getting this backwards
     shifts every colour by one material and looks almost right.
   - Version written is 150 (the version MagicaVoxel itself writes).

   Axis convention lives in voxToEngine/engineToVox below and NOWHERE else.
   ========================================================================== */

export const VOX_VERSION = 150;
export const MAX_DIM = 256;

/* ============================================================================
   Axis convention

   MagicaVoxel is Z-up; the engine is Y-up. src/sim/voxload.cpp:237-238 does
   engine = (vox.x, vox.z, -vox.y), chirality-preserving, then rebases the
   min corner to 0. We mirror that exactly. Because -vox.y is negative for all
   vox.y >= 0, the rebase is what brings the model back into the positive
   octant; a model of size (sx, sy, sz) in vox space becomes (sx, sz, sy) in
   engine space with engineZ = (sy - 1) - voxY.

   These two functions are inverses over a known vox-space size. Every other
   place in the editor that needs to convert calls one of them.
   ========================================================================== */

// vox cell (x,y,z) inside a model of vox-space size {x,y,z} -> engine cell.
export function voxToEngine(vx, vy, vz, size) {
  return { x: vx, y: vz, z: (size.y - 1) - vy };
}

// engine cell -> vox cell, given the same vox-space size. Exact inverse.
export function engineToVox(ex, ey, ez, size) {
  return { x: ex, y: (size.y - 1) - ez, z: ey };
}

// Engine-space dimensions of a model whose vox-space size is `size`.
export const voxSizeToEngine = size => ({ x: size.x, y: size.z, z: size.y });
// ...and back. Same swap, so this is its own inverse, but naming both keeps
// call sites readable.
export const engineSizeToVox = size => ({ x: size.x, y: size.z, z: size.y });

